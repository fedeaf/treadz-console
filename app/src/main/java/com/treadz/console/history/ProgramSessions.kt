package com.treadz.console.history

import com.treadz.console.programs.personalised.CouchToFiveK
import com.treadz.console.userdata.UserData
import com.treadz.console.userdata.WorkoutSummary
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.flow.flatMapLatest
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.flow.map

/**
 * The workouts of the active user that belong to one program or to one generator of personalised programs, newest first:
 * the sessions each program shows inside itself. [couchSessions] has the Couch to 5K session (1-27) of each workout that
 * was one, by workout id, for its row.
 */
data class ProgramSessions(
    val workouts: List<WorkoutSummary> = emptyList(),
    val couchSessions: Map<Long, Int> = emptyMap(),
) {
    companion object {

        /** The workouts that ran the standard or own program [programId] (`WorkoutSummary.programId`). */
        @OptIn(ExperimentalCoroutinesApi::class)
        fun ofProgram(userData: UserData, programId: String): Flow<ProgramSessions> =
            userData.profiles.activeUser.flatMapLatest { user ->
                if (user == null) flowOf(ProgramSessions()) else userData.workouts.workouts(user.id).map { list -> ProgramSessions(list.filter { it.programId == programId }) }
            }

        /** The workouts generated by [generatorId] (`WorkoutSummary.generatorId`): the sessions are not saved as programs. */
        @OptIn(ExperimentalCoroutinesApi::class)
        fun ofGenerator(userData: UserData, generatorId: String): Flow<ProgramSessions> =
            userData.profiles.activeUser.flatMapLatest { user ->
                if (user == null) {
                    flowOf(ProgramSessions())
                } else {
                    combine(userData.workouts.workouts(user.id), couchSessionNumbers(userData, user.id, generatorId)) { list, couch ->
                        ProgramSessions(list.filter { it.generatorId == generatorId }, couch)
                    }
                }
            }

        /**
         * The Couch to 5K session number of each workout of [userId] that was one (it lives in the session record); empty for
         * any other [generatorId].
         */
        fun couchSessionNumbers(userData: UserData, userId: Long, generatorId: String = CouchToFiveK.ID): Flow<Map<Long, Int>> =
            if (generatorId != CouchToFiveK.ID) {
                flowOf(emptyMap())
            } else {
                userData.workouts.sessionRecords(userId, CouchToFiveK.ID).map { records ->
                    records.mapNotNull { r -> CouchToFiveK.sessionOf(r.record)?.let { r.workoutId to it } }.toMap()
                }
            }
    }
}
