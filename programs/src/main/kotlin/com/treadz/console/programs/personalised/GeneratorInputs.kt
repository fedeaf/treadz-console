package com.treadz.console.programs.personalised

import com.treadz.console.analysis.fitness.SelfRatedFitness
import com.treadz.console.analysis.fitness.Sex
import com.treadz.console.programs.fitness.FitnessProfile
import com.treadz.console.programs.fitness.HeartRateMaxOrigin
import com.treadz.console.programs.heartrate.HeartRateProfile
import java.util.UUID

/** Whether a generated session is walked (speed fixed, incline moves) or run (speed moves, incline 1 %). */
enum class ExerciseMode { Walk, Run }

/**
 * What the generators know about the user. Plain values: the app fills them from its own profile, weight log and
 * fitness profile.
 *
 * @property heightCm Height; with [weightKg] it gives the BMI of the non-exercise VO2max estimate. When either is missing
 *   a BMI of [IntensityEstimator.DEFAULT_BMI] is assumed.
 * @property fitnessProfile The live fitness profile (tests); `null` or partial when the user has done no tests.
 * @property heartRate Effective maximum heart rate (manual > measured > estimated) and the resting heart rate if known.
 * @property maxHeartRateOrigin Where [HeartRateProfile.maxBpm] comes from; [HeartRateMaxOrigin.Estimated] counts as an
 *   estimated reference (see [IntensityReferences.estimatedFor]).
 */
data class GeneratorProfile(
    val sex: Sex,
    val ageYears: Int,
    val heightCm: Double?,
    val weightKg: Double?,
    val selfRatedFitness: SelfRatedFitness?,
    val fitnessProfile: FitnessProfile?,
    val heartRate: HeartRateProfile,
    val maxHeartRateOrigin: HeartRateMaxOrigin = HeartRateMaxOrigin.Estimated,
)

/**
 * Everything a generator needs to produce one session. Which of the optional values a generator reads is listed in its
 * [GeneratorDescriptor.inputs]; the others are ignored.
 *
 * @property nowMillis The current time (epoch ms): today's date for the history rules.
 * @property durationMinutes Requested total duration (zone 2, tempo); `null` = the generator's default.
 * @property series Number of series (30/30); `null` = the default.
 * @property startWeek Couch to 5K: the week (1-9) the user chose to start or restart the plan at; `null` = continue from
 *   the history (or week 1 without history).
 * @property walkingSpeedKmh Comfortable walking speed; `null` = from the history (Couch to 5K) or
 *   [IntensityTranslator.DEFAULT_WALKING_SPEED_KMH].
 * @property jogSpeedAdjustmentPercent Couch to 5K: the user's ± adjustment of the jog speed (−20 to +20 %).
 * @property history Records of the previous sessions generated by this generator (others are ignored), any order.
 * @property programId Id of the generated program (a UUID).
 * @property name Name of the generated program (the UI passes its translated text); `null` = an English name.
 */
data class GeneratorRequest(
    val profile: GeneratorProfile,
    val nowMillis: Long,
    val mode: ExerciseMode = ExerciseMode.Run,
    val durationMinutes: Int? = null,
    val series: Int? = null,
    val startWeek: Int? = null,
    val walkingSpeedKmh: Double? = null,
    val jogSpeedAdjustmentPercent: Int = 0,
    val history: List<GeneratedSessionRecord> = emptyList(),
    val programId: String = UUID.randomUUID().toString(),
    val name: String? = null,
)
